num1 = int(input("Enter first number: "))  # Taking input from the user and converting it to an integer
num2 = int(input("Enter second number: "))  # Taking input from the user and converting it to an integer

print("Addition of two numbers is : ", num1 + num2)  # Printing the sum of num1 and num2
print("Subtraction of two numbers is : ", num1 - num2)  # Printing the difference of num1 and num2
print("Multiplication of two numbers is : ", num1 * num2)  # Printing the product of num1 and num2
print("Division of two numbers is : ", num1 / num2)  # Printing the quotient of num1 and num2
print("Integer Division of two numbers is : ", num1 // num2)  # Printing the integer division of num1 and num2
print("Modulus of two numbers is : ", num1 % num2)  # Printing the remainder of num1 divided by num2
print("Exponentiation of two numbers is : ", num1 ** num2)  # Printing num1 raised to the power of num2


